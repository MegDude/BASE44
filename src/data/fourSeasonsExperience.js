function categoryKey(parts) {
  return parts
    .filter(Boolean)
    .join(" ")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_");
}

function fourSeasonsEntity(input) {
  const {
    id,
    kind,
    category,
    title,
    lat,
    lng,
    imageUrl,
    eyebrow,
    headline,
    subhead,
    description,
    scheduleLabel,
    highlights = [],
    residentPerk,
    primaryCta,
    relatedEntityIds = [],
    pinKey,
    actions,
    tags = [],
    searchKeywords = [],
    bestFor,
    knownFor,
    ...extraFields
  } = input;

  return {
    ...FOUR_SEASONS_BASE,
    ...extraFields,
    id,
    name: title,
    title,
    shortTitle: title,
    type: kind === "experience" ? "venue" : kind,
    kind,
    entityType: kind,
    sourceType: kind === "event" ? "event" : kind === "perk" ? "offer" : kind,
    markerType: kind,
    detailDrawerType: kind,
    pinKey,
    category,
    category_key: categoryKey(["four seasons", kind, category, title, eyebrow, ...highlights]),
    latitude: lat,
    longitude: lng,
    image: imageUrl,
    imageUrl,
    cardEyebrow: eyebrow,
    drawerHeadline: headline,
    summary: subhead,
    description,
    scheduleLabel,
    timing: scheduleLabel,
    offer: residentPerk?.copy,
    hasPerk: Boolean(residentPerk),
    perk: residentPerk
      ? {
          title: residentPerk.label,
          value: residentPerk.copy,
          description: residentPerk.copy,
          isActive: true,
        }
      : undefined,
    highlights,
    bestFor: bestFor || highlights,
    knownFor: knownFor || highlights,
    residentQuickFacts: [scheduleLabel, ...highlights].filter(Boolean).slice(0, 5),
    primaryAction: primaryCta?.label,
    secondaryAction: "Get Directions",
    actions: actions || [primaryCta?.label, "Get Directions", "Save"].filter(Boolean),
    website: primaryCta?.href,
    related: relatedEntityIds,
    relatedEntityIds,
    tags: ["Four Seasons", eyebrow, category, ...highlights, ...tags].filter(Boolean),
    searchKeywords: [
      "four seasons austin",
      "four seasons downtown",
      title,
      category,
      eyebrow,
      ...highlights,
      ...searchKeywords,
    ],
  };
}

