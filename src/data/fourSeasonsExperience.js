export function getFourSeasonsExperienceUpdate(item) {
  const text = [item?.id, item?.slug, item?.name, item?.title, item?.brand, item?.raw?.id, item?.raw?.name, item?.raw?.title]
    .filter(Boolean)
    .join(" ")
    .toLowerCase();

  if (!text) return null;
  const isResidentialFourSeasons =
    text.includes("four seasons residences") ||
    text.includes("four-seasons-residences") ||
    text.includes("residential") ||
    text.includes("condo") ||
    text.includes("listing") ||
    text.includes("rental");
  if (isResidentialFourSeasons && !text.includes("four-seasons-congress-guest-dining-campaign")) return null;
  if (text.includes("four-seasons-congress-guest-dining-campaign")) return FOUR_SEASONS_HOSPITALITY_ACCESS;
  if (text.includes("four seasons guest dining campaign")) return FOUR_SEASONS_HOSPITALITY_ACCESS;
  if (text.includes("four seasons hotel austin")) return {
    ...FOUR_SEASONS_HOSPITALITY_ACCESS,
    id: item?.id || "partner-four-seasons",
    name: "Four Seasons Hotel Austin",
    title: "Four Seasons Hotel Austin",
  };
  if (text.includes("partner-four-seasons")) return {
    ...FOUR_SEASONS_HOSPITALITY_ACCESS,
    id: item?.id || "partner-four-seasons",
    name: item?.name || "Four Seasons Hotel Austin",
    title: item?.title || item?.name || "Four Seasons Hotel Austin",
  };

  return null;
}
