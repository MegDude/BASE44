export function getBrandActivationIntelligence(entity = {}) {
  const ids = [
    entity.id,
    entity.parentId,
    entity.raw?.id,
    entity.raw?.parentId,
  ].filter(Boolean);
  return ids.map((id) => brandActivationIntelligenceByEntityId[id]).find(Boolean) || null;
}

export function getBrandActivationRoutesForEntity(entity = {}) {
  const intelligence = getBrandActivationIntelligence(entity);
  if (!intelligence) return [];
  return brandActivationRoutes.filter((route) => intelligence.routeIds.includes(route.routeId) || route.stopPinIds.includes(intelligence.entityId));
}
