export function getSushiEntityUpdate(item) {
  const text = [item?.id, item?.slug, item?.name, item?.title, item?.raw?.id, item?.raw?.name, item?.raw?.title]
    .filter(Boolean)
    .join(" ")
    .toLowerCase();
  if (!text) return null;
  return sushiVenueEntities.find((venue) => {
    const aliases = [venue.id, venue.name, venue.title, venue.shortTitle, ...(venue.searchKeywords || [])]
      .filter(Boolean)
      .map((value) => String(value).toLowerCase());
    return aliases.some((alias) => alias && text.includes(alias));
  }) || null;
}
