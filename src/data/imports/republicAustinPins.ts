function slug(value: string) {
  return value
    .toLowerCase()
    .trim()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function categoryKey(category: RepublicAustinPin["category"]) {
  if (category === "EV Charging") return "ev_charging mobility republic_austin";
  if (category === "Transit") return "transit metro mobility republic_austin";
  if (category === "Grocery") return "grocery pharmacy retail republic_austin";
  if (category === "Culture") return "culture entertainment civic events republic_austin";
  if (category === "Fitness") return "fitness wellness republic_austin";
  if (category === "Hotel") return "hotel hospitality republic_austin";
  return "dining bars restaurants republic_austin";
}

function pinKey(category: RepublicAustinPin["category"]) {
  if (category === "EV Charging" || category === "Transit") return "mobility";
  if (category === "Grocery") return "retail";
  if (category === "Culture") return "culture";
  if (category === "Fitness") return "wellness";
  if (category === "Hotel") return "hotel";
  return "dining";
}

function partnerType(category: RepublicAustinPin["category"]) {
  if (category === "Hotel") return "hotels";
  if (category === "Culture" || category === "Transit" || category === "EV Charging") return "civic";
  return "venues";
}

function defaultTags(seed: Seed) {
  return [
    "Republic Austin",
    seed.sourceCategory,
    seed.category,
    seed.district,
    seed.mapTag,
    ...(seed.tags || []),
  ].filter(Boolean) as string[];
}

