export const skippedRepublicAustinPins = seedRecords
  .map(record)
  .filter((pin) => !Number.isFinite(pin.lat) || !Number.isFinite(pin.lng));

export function dedupeRepublicAustinPins(pins: RepublicAustinPin[]) {
  const seen = new Set<string>();

  return pins.filter((pin) => {
    const key = [slug(pin.name), slug(pin.sourceCategory), Number(pin.longitudeHint ?? pin.lng ?? 0).toFixed(5)].join("|");
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

export function getRepublicAustinMapPlaces() {
  return republicAustinPins
    .filter((pin) => Number.isFinite(pin.lat) && Number.isFinite(pin.lng))
    .map((pin) => ({
      id: pin.id,
      name: pin.name,
      type: pin.category === "Hotel" ? "hotel" : pin.category === "Culture" || pin.category === "Transit" || pin.category === "EV Charging" ? "civic" : "venue",
      partnerType: partnerType(pin.category),
      category: `${pin.category} / Republic Austin`,
      category_key: categoryKey(pin.category),
      markerType: "standard",
      detailDrawerType: "republic-austin",
      pinKey: pinKey(pin.category),
      latitude: pin.lat,
      longitude: pin.lng,
      district: pin.district,
      address: pin.addressHint,
      summary: pin.shortDescription,
      description: pin.shortDescription,
      drawerCopy: pin.residentCopy,
      partnerInsight: pin.partnerCopy,
      deals_offers: pin.recommendedPerk,
      specials: pin.recommendedPerk,
      tags: pin.tags,
      republicIcon: pin.icon,
      republicAustinPin: pin,
      isRepublicAustinPin: true,
      source: "Republic Austin",
    }));
}
