function buildRestaurantRecord(record) {
  const image = venueImages[record.id]?.src;
  const perk = {
    title: record.perkTitle,
    value: record.perkLabel,
    description: record.perkDescription,
    terms: record.perkFinePrint,
    isActive: true,
  };

  return {
    ...record,
    name: record.title,
    kind: "venue",
    partnerType: "venues",
    category_key: [
      "venue",
      "restaurant",
      "restaurant_food",
      "resident_perk",
      record.category,
      record.subcategory,
      record.district,
      record.neighborhood,
      ...(record.bestFor || []),
      ...(record.searchKeywords || []),
    ]
      .filter(Boolean)
      .join(" ")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "_"),
    image,
    imageUrl: image,
    heroImage: image,
    galleryImages: [image, record.secondaryImage].filter(Boolean),
    summary: record.cardDescription,
    description: record.drawerBody,
    website: record.website,
    offer: record.perkTitle,
    deals_offers: record.perkTitle,
    specials: record.perkDescription,
    terms: record.perkFinePrint,
    perk,
    hasPerk: true,
    pinKey: record.category === "Drinks" ? "cocktail" : "dining",
    tags: [
      record.category,
      record.subcategory,
      record.district,
      record.neighborhood,
      record.perkLabel,
      record.perkTitle,
      ...(record.bestFor || []),
      ...(record.searchKeywords || []),
    ].filter(Boolean),
    residentSearchIntents: [
      "All",
      record.category,
      "Perks",
      record.district,
      record.neighborhood,
      "Tonight",
      "Date night",
      "Dinner nearby",
      "Happy hour nearby",
      "Client dinner",
      ...(record.residentSearchIntents || []),
    ],
    residentDrawer: {
      eyebrow: record.cardEyebrow,
      headline: record.drawerHeadline,
      body: record.drawerBody,
      perk,
      bestFor: record.bestFor,
      primaryCTA: record.primaryCTA,
      secondaryCTA: record.secondaryCTA,
    },
    primaryAction: record.primaryCTA,
    secondaryAction: record.secondaryCTA,
    source: "Downtown Perks downtown core restaurant perk update",
  };
}

