const RESTAURANT_LOOKUP = DOWNTOWN_CORE_RESTAURANT_RECORDS.flatMap((record) => {
  const idKey = String(record.id || "").toLowerCase();
  const titleKey = String(record.title || "").toLowerCase();
  return [idKey, titleKey, ...(record.aliases || []).map((alias) => String(alias).toLowerCase())]
    .filter(Boolean)
    .map((key) => [key, record]);
});

export function getDowntownCoreRestaurantUpdate(item) {
  const haystack = [
    item?.id,
    item?.slug,
    item?.name,
    item?.title,
    item?.shortTitle,
    item?.currentMapName,
    item?.raw?.id,
    item?.raw?.name,
    item?.raw?.title,
  ]
    .filter(Boolean)
    .join(" ")
    .toLowerCase();

  if (!haystack) return null;

  const exactId = RESTAURANT_LOOKUP.find(([key]) => key && haystack.split(/\s+/).includes(key));
  if (exactId) return exactId[1];

  const match = RESTAURANT_LOOKUP.find(([key]) => key && haystack.includes(key));
  return match ? match[1] : null;
}
